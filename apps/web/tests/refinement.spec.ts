import { expect, test } from "@playwright/test";
import { chooseArthur, signIn, uploadCorpus } from "./fixtures";

test.skip(process.env.VISION_TEST_WORKSPACE !== "1", "Requires isolated workspace API/worker fixtures");
test("two tabs reject stale refinement, retain locked canon and revisit immutable scoped history", async ({ page, context }) => {
  test.setTimeout(90000);
  await signIn(page);
  const workId = await uploadCorpus(page, "Refinement history");
  await chooseArthur(page);
  await page.getByLabel("Story moment", { exact: true }).fill("after the war");
  await page.getByLabel("Scene context", { exact: true }).fill("at home");
  const response = page.waitForResponse(r => /\/visualizations$/.test(r.url()) && r.request().method() === "POST");
  await page.getByRole("button", { name: "Create visual specification", exact: true }).click();
  const original = (await (await response).json()).visualization;
  const other = await context.newPage();
  await other.goto(`/works/${workId}`);
  await chooseArthur(other);
  await expect(other.getByRole("button", { name: "Open Arthur revision 1", exact: true })).toBeVisible();
  await other.getByRole("button", { name: "Open Arthur revision 1", exact: true }).click();
  await expect(other.getByRole("region", { name: "Refine presentation" })).toContainText("Editing revision 1");
  await page.getByLabel("Refinement style", { exact: true }).fill("charcoal");
  await page.getByRole("combobox", { name: "Refinement creative mode", exact: true }).selectOption("interpretation");
  await page.getByRole("checkbox", { name: /Lock Arthur attire: plain linen shirt/ }).check();
  await page.getByRole("button", { name: "Save new revision", exact: true }).click();
  await expect(page.getByRole("region", { name: "Visual specification", exact: true })).toContainText("revision 2");
  await other.getByLabel("Refinement style", { exact: true }).fill("ink wash");
  await other.getByRole("button", { name: "Save new revision", exact: true }).click();
  const refinement = other.getByRole("region", { name: "Refine presentation" });
  await expect(refinement.getByRole("alert")).toContainText("changed");
  await expect(other.getByLabel("Refinement style", { exact: true })).toHaveValue("ink wash");
  await other.getByRole("button", { name: "Reload current revision", exact: true }).click();
  await expect(refinement).toContainText("Editing revision 2");
  await expect(other.getByRole("checkbox", { name: /Lock Arthur attire: plain linen shirt/ })).toBeChecked();
  await expect(other.getByLabel("Refinement style", { exact: true })).toHaveValue("ink wash");
  await other.getByRole("button", { name: "Save new revision", exact: true }).click();
  await expect(other.getByRole("region", { name: "Visual specification", exact: true })).toContainText("revision 3");
  const stored = await (await other.request.get(`/api/v1/works/${workId}/visualizations/${original.id}`)).json();
  expect(stored.result.data.subject).toEqual(original.result.data.subject);
  expect(stored.request.style).toBe("ink wash");
  await other.getByRole("button", { name: "Open Arthur revision 3", exact: true }).click();
  await other.getByRole("button", { name: "View revision 1", exact: true }).click();
  const old = other.getByRole("region", { name: "Visual specification", exact: true });
  await expect(old).toContainText("revision 1");
  await expect(other.getByRole("region", { name: "Refine presentation" })).toHaveCount(0);
  await old.getByRole("button", { name: /Arthur · attire:/ }).click();
  await expect(old.getByRole("region", { name: "Source reader" }).locator('mark[data-selected=true]')).toBeVisible();
  let release!: () => void;
  let started!: () => void;
  const held = new Promise<void>(resolve => { release = resolve; });
  const requested = new Promise<void>(resolve => { started = resolve; });
  const pattern = `**/visualizations/${original.id}?*`;
  await other.route(pattern, async route => {
    const response = await route.fetch();
    started(); await held; await route.fulfill({ response });
  });
  await other.getByRole("button", { name: "Open Arthur revision 3", exact: true }).click();
  await requested;
  await other.getByLabel("Describe the view", { exact: true }).fill("A new draft view");
  await expect(old).toHaveCount(0);
  release();
  await expect(other.getByRole("button", { name: "Reload saved views", exact: true })).toBeEnabled();
  await expect(old).toHaveCount(0);
  await other.unroute(pattern);
  await chooseArthur(other, 1);
  await expect(old).toHaveCount(0);
  await expect(other.getByText("No saved specifications in this reading scope.")).toBeVisible();
  await expect(other.getByRole("button", { name: /Open Arthur revision/ })).toHaveCount(0);
});
